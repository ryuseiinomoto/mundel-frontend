// ── Progress utilities (client-side only) ──
const PROGRESS_KEY = "mundel_course_progress"

export function getStep(id: number): Step | undefined {
  return STEPS.find((s) => s.id === id)
}

export function getProgress(): number[] {
  if (typeof window === "undefined") return []
  try {
    return JSON.parse(localStorage.getItem(PROGRESS_KEY) ?? "[]")
  } catch {
    return []
  }
}

export function markComplete(stepId: number): void {
  const progress = getProgress()
  if (!progress.includes(stepId)) {
    localStorage.setItem(PROGRESS_KEY, JSON.stringify([...progress, stepId]))
  }
}

export function isComplete(stepId: number): boolean {
  return getProgress().includes(stepId)
}

export function isUnlocked(stepId: number): boolean {
  if (stepId === 1) return true
  return isComplete(stepId - 1)
}

export function getCompletedCount(): number {
  return getProgress().length
}
